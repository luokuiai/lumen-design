const translationEntries = Object.entries(demoTranslations)
  .sort(([left], [right]) => right.length - left.length);

export const translateDemoText = (text: string) => translationEntries.reduce(
  (result, [source, target]) => result.replaceAll(source, target),
  text,
);

const localizeValue = (value: unknown): unknown => {
  if (typeof value === 'string') return translateDemoText(value);
  if (Array.isArray(value)) return value.map(localizeValue);
  if (isValidElement(value)) {
    const element = value as ReactElement<Record<string, unknown>>;
    const props = Object.fromEntries(
      Object.entries(element.props).map(([key, propValue]) => [
        key,
        key === 'children'
          ? Children.map(propValue as ReactNode, (child) => localizeValue(child) as ReactNode)
          : localizeValue(propValue),
      ]),
    );
    return cloneElement(element, props);
  }
  if (value && typeof value === 'object' && Object.getPrototypeOf(value) === Object.prototype) {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localizeValue(item)]),
    );
  }
  return value;
};

export const localizeDemoNode = (node: ReactNode) => localizeValue(node) as ReactNode;
